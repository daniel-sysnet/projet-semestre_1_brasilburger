-- Table: paiement
CREATE TABLE paiement (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    date_paiement TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    montant DOUBLE PRECISION NOT NULL,
