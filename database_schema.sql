-- Table: client
CREATE TABLE client (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    telephone VARCHAR(20) NOT NULL,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX UNIQ_C7440455450FF010 ON client (telephone);

-- Table: gestionnaire
CREATE TABLE gestionnaire (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    telephone VARCHAR(20) NOT NULL,
    login VARCHAR(180) NOT NULL,
    password VARCHAR(255) NOT NULL,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX UNIQ_F4461B20AA08CB10 ON gestionnaire (login);

-- Table: zone
CREATE TABLE zone (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nom VARCHAR(255) NOT NULL,
    prix DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (id)
);

-- Table: livreur
CREATE TABLE livreur (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    telephone VARCHAR(20) NOT NULL,
    zone_id INT DEFAULT NULL,
    PRIMARY KEY (id)
);
CREATE INDEX IDX_EB7A4E6D9F2C3FAB ON livreur (zone_id);

-- Table: burger
CREATE TABLE burger (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nom VARCHAR(255) NOT NULL,
    description TEXT DEFAULT NULL,
    prix DOUBLE PRECISION NOT NULL,
    image VARCHAR(255) DEFAULT NULL,
    actif BOOLEAN NOT NULL,
    PRIMARY KEY (id)
);

-- Table: menu
CREATE TABLE menu (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nom VARCHAR(255) NOT NULL,
    description TEXT DEFAULT NULL,
    image VARCHAR(255) DEFAULT NULL,
    prix DOUBLE PRECISION NOT NULL,
    actif BOOLEAN NOT NULL,
    PRIMARY KEY (id)
);

-- Table: complement
CREATE TABLE complement (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nom VARCHAR(255) NOT NULL,
    description TEXT DEFAULT NULL,
    prix DOUBLE PRECISION NOT NULL,
    image VARCHAR(255) DEFAULT NULL,
    actif BOOLEAN NOT NULL,
    PRIMARY KEY (id)
);

-- Table: commande
CREATE TABLE commande (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    date_commande TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    etat VARCHAR(50) NOT NULL,
    type VARCHAR(50) NOT NULL,
    client_id INT NOT NULL,
    zone_id INT DEFAULT NULL,
    livreur_id INT DEFAULT NULL,
    PRIMARY KEY (id)
);
